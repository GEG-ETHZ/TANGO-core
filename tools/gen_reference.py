"""Generate the config-key and output reference pages from the code.

Writes Markdown fragments into ``docs/reference/generated/`` that the docs
site includes with snippets. Every table is derived from the code itself:

- Config keys: the ``Field(frozen=True)`` fields of each registered
  component class (``components/registry.py``) and the top-level schemas in
  ``core/specs.py``, with each field's attribute docstring as description.
  A component field whose type is itself a pydantic model (the segment and
  ``raft:`` blocks of a ``grouped_subsurface``) is a nested block, with its
  own key table, or a pointer to the component whose keys it takes.
  Keys a component receives from ``common``, ``layout`` or ``sim_config``
  (``workflows/workflow.py::_PROTECTED_COMPONENT_KEYS``) are listed separately.
- Outputs: the scalar per-timestep fields of each component's ``*History``
  dataclass (the ``<stem>.smry.csv`` columns), including a nested block's
  own history (columns ``<name>.<block>_<value>``), and the economic state
  (the ``<stem>.econ.csv`` columns).
- Surface plant: the TESPy node types and node roles a ``power_plant`` graph
  accepts.

A docstring ending in ``TODO(docs): drafted, review.`` is shown with a
*draft* tag; a docstring that is only a ``TODO(docs)`` marker is shown as
*undocumented*.

Usage:
    uv run python tools/gen_reference.py          # write the fragments
    uv run python tools/gen_reference.py --check  # exit 1 if they are stale
"""

from __future__ import annotations

import argparse
import ast
import dataclasses
import inspect
import re
import sys
import textwrap
import typing
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from tango_core.components.economic.doublet import EconomicState
from tango_core.components.registry import COMPONENT_REGISTRY
from tango_core.components.surface import graph as surface_graph
from tango_core.core.policies import ComponentRole
from tango_core.core.specs import Common, Description, Layout, SimConfig
from tango_core.workflows.workflow import _PROTECTED_COMPONENT_KEYS

OUT_DIR = Path(__file__).parents[1] / "docs" / "reference" / "generated"
HEADER = "<!-- Generated by tools/gen_reference.py from the code. Do not edit; edit the docstrings. -->\n\n"
TODO_RE = re.compile(r"\s*TODO\(docs\):.*$", re.DOTALL)
#: Component types documented together on one page, in reading order.
GROUPS: dict[str, tuple[str, ...]] = {
    "reservoir": ("reservoir",),
    "well": ("injection_well", "production_well", "production_well_with_pump", "horizontal_well"),
    "surface": ("surface",),
    "grouped_subsurface": ("grouped_subsurface",),
    "economic": ("economic",),
}
#: Where a protected key comes from in the config.
PROTECTED_SOURCE = {
    "common": "the `common:` block",
    "well_spacing": "`layout.well_spacing`",
    "well_pattern": "`layout.well_pattern`",
    "dt_years": "`sim_config.dt_years`",
    "target_extraction_pressure": "`sim_config.target_extraction_pressure`",
}


def attribute_docstrings(cls: type) -> dict[str, str]:
    """Return the attribute docstrings of ``cls`` and its tango base classes.

    Args:
        cls: A class whose attributes are documented with a string literal
            directly after their annotated assignment.

    Returns:
        Mapping of attribute name to docstring; subclasses override bases.
    """
    docs: dict[str, str] = {}
    for klass in reversed(cls.__mro__):
        if not klass.__module__.startswith("tango."):
            continue
        tree = ast.parse(textwrap.dedent(inspect.getsource(klass)))
        body = tree.body[0].body if tree.body and isinstance(tree.body[0], ast.ClassDef) else []
        for node, nxt in zip(body, body[1:], strict=False):
            is_doc = isinstance(nxt, ast.Expr) and isinstance(nxt.value, ast.Constant)
            if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and is_doc:
                docs[node.target.id] = inspect.cleandoc(str(nxt.value.value))  # type: ignore[attr-defined]
    return docs


def describe(doc: str | None) -> str:
    """Render a docstring as one table cell, tagging review markers.

    Args:
        doc: The attribute docstring, or None if there is none.

    Returns:
        A single-line Markdown cell.
    """
    if not doc:
        return "*undocumented*"
    text = " ".join(TODO_RE.sub("", doc).split()).replace("``", "`").replace("|", "\\|")
    if not text:
        return "*undocumented*"
    return f"{text} *draft*" if "TODO(docs)" in doc else text


def type_name(annotation: Any) -> str:
    """Return a short, readable name for a type annotation.

    Args:
        annotation: A type annotation object.

    Returns:
        The annotation without module prefixes.
    """
    name = annotation.__name__ if isinstance(annotation, type) else str(annotation)
    return re.sub(r"\b[\w.]+\.(\w+)", r"\1", name).replace("typing.", "").replace("|", "\\|")


def default_text(model: type[BaseModel], name: str) -> str:
    """Return the default of a pydantic field, or ``required``.

    Args:
        model: The pydantic model class.
        name: The field name.

    Returns:
        A code-formatted default, ``required`` or ``computed``.
    """
    field = model.model_fields[name]
    if field.is_required():
        return "required"
    if field.default_factory is not None:
        return "computed"
    return f"`{field.default!r}`"


def keys_table(model: type[BaseModel], *, frozen_only: bool) -> str:
    """Return the config-key table of a pydantic model.

    Args:
        model: A component class or a top-level schema.
        frozen_only: Only list ``Field(frozen=True)`` fields (components).

    Returns:
        A Markdown table, plus a list of keys filled in from other blocks.
    """
    docs = attribute_docstrings(model)
    rows, inherited = [], []
    for name, field in model.model_fields.items():
        if frozen_only and not field.frozen:
            continue
        if name in _PROTECTED_COMPONENT_KEYS:
            inherited.append(f"`{name}` from {PROTECTED_SOURCE.get(name, 'another block')}")
            continue
        rows.append(
            f"| `{name}` | `{type_name(field.annotation)}` | {default_text(model, name)} | {describe(docs.get(name))} |",
        )
    table = "| Key | Type | Default | Meaning |\n|---|---|---|---|\n" + "\n".join(rows) + "\n"
    if inherited:
        table += "\nFilled in automatically, not set in this block: " + ", ".join(inherited) + ".\n"
    return table


def history_rows(history_cls: type, prefix: str, state_cls: type | None = None) -> list[str]:
    """Return one table row per scalar per-timestep field of a history class.

    Args:
        history_cls: A ``*History`` dataclass.
        prefix: Column prefix, e.g. ``<name>_``.
        state_cls: The matching ``*State`` class; its field docstrings are
            used where the history field has none (every state field has a
            history field of the same name, a CONTRIBUTING rule).

    Returns:
        Markdown table rows; non-scalar series are skipped, as in the CSV.
    """
    docs = {**(attribute_docstrings(state_cls) if state_cls else {}), **attribute_docstrings(history_cls)}
    hints = typing.get_type_hints(history_cls)
    rows = []
    for field in dataclasses.fields(history_cls):
        args = typing.get_args(hints.get(field.name))
        if typing.get_origin(hints.get(field.name)) is not list or not args or typing.get_origin(args[0]):
            continue
        rows.append(f"| `{prefix}{field.name}` | {describe(docs.get(field.name))} |")
    return rows


def block_fields(cls: type[BaseModel]) -> dict[str, type[BaseModel]]:
    """Return a component's nested config blocks: its non-frozen fields typed as a pydantic model.

    Args:
        cls: A registered component class.

    Returns:
        Mapping of block (field) name to the block's model class.
    """
    return {
        name: field.annotation
        for name, field in cls.model_fields.items()
        if not field.frozen and isinstance(field.annotation, type) and issubclass(field.annotation, BaseModel)
    }


def registry_key(cls: type) -> tuple[str, str] | None:
    """Return the ``(type, variant)`` a class is registered under, if it is a component.

    Args:
        cls: Any class.

    Returns:
        The registry key, or None.
    """
    return next((key for key, registered in COMPONENT_REGISTRY.items() if registered is cls), None)


def blocks_text(cls: type[BaseModel]) -> str:
    """Return the key tables of a component's nested config blocks.

    A block that is itself a registered component takes that component's
    keys, documented with it, so it gets a pointer instead of a table.

    Args:
        cls: A registered component class.

    Returns:
        Markdown: a table of the blocks, then one key table per block model.
    """
    blocks = block_fields(cls)
    if not blocks:
        return ""
    docs = attribute_docstrings(cls)
    rows = []
    for name, model in blocks.items():
        key = registry_key(model)
        takes = f"the keys of `{key[0]}` · `{key[1]}`" if key else f"`{model.__name__}` keys, below"
        rows.append(f"| `{name}:` | {takes} | {describe(docs.get(name))} |")
    text = "Nested blocks:\n\n| Block | Keys | Meaning |\n|---|---|---|\n" + "\n".join(rows) + "\n\n"
    for model in dict.fromkeys(m for m in blocks.values() if registry_key(m) is None):
        names = ", ".join(f"`{name}:`" for name, m in blocks.items() if m is model)
        text += f"`{model.__name__}` ({names}):\n\n" + keys_table(model, frozen_only=True) + "\n"
    return text


def block_outputs_text(cls: type[BaseModel]) -> str:
    """Return the output columns of a component's nested blocks that keep their own history.

    Args:
        cls: A registered component class.

    Returns:
        Markdown: a table per block history, or a pointer for a block that
        is itself a registered component.
    """
    text = ""
    for name, model in block_fields(cls).items():
        if "history" not in model.model_fields:
            continue
        key = registry_key(model)
        if key:
            text += f"Columns `<name>.{name}_<value>`: the outputs of `{key[0]}` · `{key[1]}`.\n\n"
            continue
        history_cls = model.model_fields["history"].annotation
        state_cls = model.model_fields["state"].annotation if "state" in model.model_fields else None
        state_cls = state_cls if isinstance(state_cls, type) else None
        rows = (
            history_rows(history_cls, f"<name>.{name}_", state_cls) if isinstance(history_cls, type) else []
        )
        if rows:
            text += (
                f"`{name}:` block (`{model.__name__}`):\n\n| Column | Meaning |\n|---|---|\n"
                + "\n".join(rows)
                + "\n\n"
            )
    return text


def component_fragments(group: str) -> tuple[str, str]:
    """Return the config and output fragments for one component group.

    Args:
        group: A key of ``GROUPS``.

    Returns:
        The config-key fragment and the output fragment.
    """
    config, outputs = [HEADER], [HEADER]
    for (comp_type, variant), cls in sorted(COMPONENT_REGISTRY.items()):
        if comp_type not in GROUPS[group]:
            continue
        title = f"### `{comp_type}` · `{variant}` → `{cls.__name__}`\n\n"
        config.append(title + keys_table(cls, frozen_only=True) + "\n" + blocks_text(cls))
        if group == "economic":
            continue
        history_cls = cls.model_fields["history"].annotation
        state_cls = cls.model_fields["state"].annotation if "state" in cls.model_fields else None
        state_cls = state_cls if isinstance(state_cls, type) else None
        rows = history_rows(history_cls, "<name>_", state_cls) if isinstance(history_cls, type) else []
        if rows:
            outputs.append(
                title
                + "| Column | Meaning |\n|---|---|\n"
                + "\n".join(rows)
                + "\n\n"
                + block_outputs_text(cls),
            )
    if group == "economic":
        rows = history_rows_state(EconomicState)
        outputs.append("| Column | Meaning |\n|---|---|\n" + "\n".join(rows) + "\n")
    return "".join(config), "".join(outputs)


def history_rows_state(state_cls: type) -> list[str]:
    """Return one table row per field of the economic state (``.econ.csv``).

    Args:
        state_cls: The ``EconomicState`` dataclass.

    Returns:
        Markdown table rows.
    """
    docs = attribute_docstrings(state_cls)
    return [f"| `{f.name}` | {describe(docs.get(f.name))} |" for f in dataclasses.fields(state_cls)]


def surface_nodes_fragment() -> str:
    """Return the node types and roles a ``power_plant`` graph accepts.

    Returns:
        A Markdown fragment.
    """
    types = getattr(surface_graph, "_COMPONENT_TYPES")  # noqa: B009
    rows = "\n".join(f"| `{name}` | `tespy.components.{tespy}` |" for name, tespy in sorted(types.items()))
    roles = ", ".join(f"`{role.value}`" for role in ComponentRole)
    return (
        HEADER
        + "| Node `type` | TESPy class |\n|---|---|\n"
        + rows
        + "\n| `PumpOrValve` | resolved to a valve or a compressor at solve time |\n\n"
        + f"Node `role` (optional): {roles}.\n"
    )


def fragments() -> dict[str, str]:
    """Return every generated fragment, keyed by file name.

    Returns:
        Mapping of file name to Markdown content.
    """
    out: dict[str, str] = {}
    for name, model in (
        ("common", Common),
        ("layout", Layout),
        ("sim_config", SimConfig),
        ("description", Description),
    ):
        out[f"config-{name}.md"] = HEADER + keys_table(model, frozen_only=False)
    for group in GROUPS:
        out[f"config-{group}.md"], out[f"outputs-{group}.md"] = component_fragments(group)
    out["surface-nodes.md"] = surface_nodes_fragment()
    # exactly one trailing newline, as the end-of-file-fixer hook leaves it
    return {name: content.rstrip("\n") + "\n" for name, content in out.items()}


def main() -> int:
    """Write the fragments, or check that they are up to date.

    Returns:
        The process exit code.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the fragments are stale")
    args = parser.parse_args()
    stale = []
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    expected = fragments()
    for name, content in expected.items():
        path = OUT_DIR / name
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(name)
        if not args.check:
            path.write_text(content, encoding="utf-8")
    # a fragment no longer generated (renamed or removed group) would otherwise linger
    for path in sorted(OUT_DIR.glob("*.md")):
        if path.name not in expected:
            stale.append(path.name)
            if not args.check:
                path.unlink()
    if args.check and stale:
        message = f"Stale reference pages: {', '.join(stale)}. Run: uv run python tools/gen_reference.py\n"
        sys.stderr.write(message)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
