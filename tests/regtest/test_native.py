import sys
import os
import pandas as pd
import pytest
from pathlib import Path
sys.path.append(os.path.join(str(Path(__file__).parent.parent.parent), 'src'))

from tango.runner import Tango
from tango.utils import parse_args, set_logger
from tango.optimizerr import Optimizer

examples_dir = os.path.join(str(Path(__file__).parent.parent.parent), 'examples')

def run(fname) -> None:
    """
    Executes the workflow. If the input file specifies optimization in the specs,
    uses the optimizer. Otherwise, runs the regular Tango workflow.
    """
    tango = Tango(fname)

    optimizer = None
    if "optimization" in tango.specs:
        optimizer = Optimizer(tango, tango.specs)

    if optimizer:
        print(f"Optimization detected for {fname}. Executing optimizer...")
        optimizer.execute()
    else:
        print(f"No optimization detected for {fname}. Executing Tango workflow...")
        tango.execute()

def get_val(fname) -> float:
    """
    Reads the .econ.csv file corresponding to the input file and extracts the LCOE value.
    """
    df = pd.read_csv(fname.replace('.yml', '.econ.csv'))
    return df['LCOE'].iloc[0]

def rmFiles(fname):
    """
    Removes the output files generated by the workflow to clean up after the test.
    """
    files = [fname.replace('.yml', '.log'),
             fname.replace('.yml', '.econ.csv'),
             fname.replace('.yml', '.smry.csv')]
    for file in files:
        if os.path.exists(file):
            os.remove(file)

