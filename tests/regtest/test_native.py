import os
from pathlib import Path
from collections.abc import Sequence
import pandas as pd
import pytest

from tango.runner import Runner
from tango.core.errors import CoolPropError, SaturationPressureError, SubzeroStateVarError

EXAMPLES_DIR = Path(__file__).parents[2] / "examples"


def run(fname: Path | str) -> None:
    """Execute the workflow. If the input file specifies optimization in the specs,
    uses the optimizer. Otherwise, runs the regular Tango workflow.
    """
    runner = Runner(fname)
    runner.start()


def get_lcoe_from_file(fname) -> float:
    """Read the .econ.csv file corresponding to the input file and extracts the LCOE value."""
    df = pd.read_csv(Path(str(fname).replace(".yml", ".econ.csv")))
    return float(df["LCOE"].iloc[0])


def rm_output_files(fname):
    """
    Removes the output files generated by the workflow to clean up after the test.
    """
    # TODO: replace this with https://docs.python.org/3/library/tempfile.html
    files = [
        Path(str(fname).replace(".yml", ".log")),
        Path(str(fname).replace(".yml", ".econ.csv")),
        Path(str(fname).replace(".yml", ".smry.csv")),
    ]
    for file in files:
        if Path(file).exists():
            os.remove(file)


